import assert from 'node:assert/strict';
import { test } from 'node:test';
import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import { fileURLToPath } from 'node:url';
import { Client } from '@modelcontextprotocol/client';
import { StdioClientTransport } from '@modelcontextprotocol/client/stdio';
import { loadVOXScene } from '../src/scene.js';
import { SCENE_PRESET_TOOL_NAMES } from '../src/scenePresets.js';
import { SCENE_ANIMATION_TOOL_NAMES } from '../src/sceneAnimation.js';

const editingNames = ['add_scene_object', 'duplicate_scene_object', 'remove_scene_object', 'reparent_scene_object', 'delete_scene_layer', 'undo_scene', 'redo_scene'];
test('scene workflows, presets and registry animation bridge work together over stdio', { timeout: 30000 }, async () => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'scene-workflows-'));
  const transport = new StdioClientTransport({ command: process.execPath, args: [fileURLToPath(new URL('../dist/index.js', import.meta.url))], cwd: root, stderr: 'pipe' });
  const client = new Client({ name: 'scene-workflows-test', version: '1.0.0' });
  const exercised = new Set<string>();
  try {
    await client.connect(transport);
    const tools = (await client.listTools()).tools;
    for (const name of [...editingNames, ...SCENE_PRESET_TOOL_NAMES, ...SCENE_ANIMATION_TOOL_NAMES]) assert.ok(tools.some(t => t.name === name), `Missing tool ${name}`);
    assert.equal(tools.find(t => t.name === 'inspect_scene_animation')!.annotations?.readOnlyHint, true);
    const call = async (name: string, args: Record<string, unknown> = {}) => {
      const result = await client.callTool({ name, arguments: args });
      assert.ok(!result.isError, `${name}: ${JSON.stringify(result)}`);
      exercised.add(name);
      const text = (result.content as { text: string }[])[0]!.text;
      return /^[\[{]/.test(text) ? JSON.parse(text) : { message: text };
    };
    const { id } = await call('create_model', { sizeX: 8, sizeY: 8, sizeZ: 8 });
    await call('set_voxels', { id, voxels: [{ x: 1, y: 2, z: 3, i: 20 }] });
    const { sceneId } = await call('create_scene', { modelIds: [id] });
    const added = await call('add_scene_object', { sceneId, id, parentId: 1, layerId: 0, translation: [8, 0, 0] });
    const copy = await call('duplicate_scene_object', { sceneId, nodeId: added.nodeId, parentId: 1 });
    await call('reparent_scene_object', { sceneId, nodeId: copy.nodeId });
    await call('remove_scene_object', { sceneId, nodeId: copy.nodeId });
    await call('set_scene_layer', { sceneId, layerId: 1, attributes: { _name: 'Objects' } });
    await call('delete_scene_layer', { sceneId, layerId: 0, reassignTo: 1 });
    assert.equal((await call('undo_scene', { sceneId })).undone, true);
    assert.equal((await call('redo_scene', { sceneId })).redone, true);
    await call('set_scene_material_properties', { sceneId, index: 20, type: 'emit', emission: 0.8, flux: 2 });
    await call('apply_scene_lighting_preset', { sceneId, preset: 'night' });
    await call('set_scene_camera_pose', { sceneId, cameraId: 0, focus: [0, 0, 0], angle: [-24, -35, 0], radius: 100, fov: 45 });
    await call('set_scene_transform_keyframe', { sceneId, nodeId: added.nodeId, frameIndex: 10, translation: [16, 0, 0] });
    await call('set_scene_model_keyframe', { sceneId, nodeId: added.shapeId, frameIndex: 10, modelIndex: 0 });
    const tracks = await call('inspect_scene_animation', { sceneId });
    assert.equal(tracks.tracks.find((t: { nodeId: number }) => t.nodeId === added.nodeId).keyframes.length, 2);
    await call('remove_scene_keyframe', { sceneId, nodeId: added.nodeId, frameIndex: 10 });
    assert.equal((await call('undo_scene', { sceneId })).undone, true);
    await call('save_scene', { sceneId, path: 'out/scene.vox' });
    const decoded = loadVOXScene(path.join(root, 'out/scene.vox'));
    assert.equal(decoded.materials.find(m => m.id === 20)!.attributes._emit, '0.8');
    assert.equal(decoded.render.cameras[0]!.attributes._radius, '100');
    const loaded = await call('load_scene', { path: 'out/scene.vox' });
    assert.equal((await call('undo_scene', { sceneId: loaded.sceneId })).undone, false);
    const animation = await call('create_animation');
    await call('add_frame', { animationId: animation.id, id });
    await call('add_frame', { animationId: animation.id, id });
    const bridged = await call('animation_to_scene', { animationId: animation.id });
    assert.equal(bridged.source, 'animationRegistry');
    await call('save_scene', { sceneId: bridged.sceneId, path: 'out/animation.vox' });
    const animated = loadVOXScene(path.join(root, 'out/animation.vox'));
    const shape = animated.nodes.find(n => n.type === 'nSHP');
    assert.ok(shape?.type === 'nSHP');
    assert.equal(shape.models.length, 2);
    const expected = [...editingNames, ...SCENE_PRESET_TOOL_NAMES, ...SCENE_ANIMATION_TOOL_NAMES].sort();
    assert.deepEqual([...exercised].filter(n => expected.includes(n)).sort(), expected);
    const before = await call('get_scene_info', { sceneId });
    const refused = await client.callTool({ name: 'set_scene_camera_pose', arguments: { sceneId, cameraId: 0, focus: [0, 0, 0], angle: [0, 0, 0], radius: 100, fov: 999 } });
    assert.equal(refused.isError, true);
    assert.deepEqual(await call('get_scene_info', { sceneId }), before);
  } finally { await client.close(); await transport.close(); fs.rmSync(root, { recursive: true, force: true }); }
});
