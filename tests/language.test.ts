import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const SELF = path.join('tests', 'language.test.ts');
const TEXT_EXT = new Set(['.ts', '.json', '.md', '.yml', '.yaml', '.js']);

function walk(rel: string, out: string[]) {
  const abs = path.join(root, rel);
  if (!fs.existsSync(abs)) return;
  const st = fs.statSync(abs);
  if (st.isFile()) { out.push(rel); return; }
  for (const name of fs.readdirSync(abs)) {
    if (name === 'node_modules' || name === 'dist' || name === '.git') continue;
    walk(path.join(rel, name), out);
  }
}

function scannedFiles(): string[] {
  const files: string[] = [];
  for (const entry of ['src', 'tests', 'README.md', 'client-config', '.github', 'package.json']) walk(entry, files);
  return files.filter(f => f !== SELF && TEXT_EXT.has(path.extname(f)));
}

const denied: Array<[string, RegExp]> = [
  ['city-specific or locale-specific term', /\b(ankara|turk|turkish|turkey|arabesk|rak[iı]|saz|karakter|bina|kule|araba)\b/i],
  ['locale-specific role or type', /\b(konsomatris|musteri|garson|asci|polis|mafya|behzat\w*|sapkali|nostalgic|barman)\b/i],
  ['locale-specific prompt keyword', /\\d\+\)\\s\*kat|\bkat\b|\(ev\|/i],
  ['assistant trace', /chatgpt|openai|copilot|generated by|co-authored|assistant|\bllm\b|gpt-/i],
  ['old product name', /magica-mcp|set_magica_path/i],
];

test('tracked text files are ASCII-only English without locale-specific or tool-trace terms', () => {
  const problems: string[] = [];
  for (const file of scannedFiles()) {
    const lines = fs.readFileSync(path.join(root, file), 'utf8').split(/\r?\n/);
    lines.forEach((line, idx) => {
      const loc = `${file}:${idx + 1}`;
      const nonAscii = /[^\x00-\x7F]/.exec(line);
      if (nonAscii) problems.push(`${loc}: non-ASCII character U+${nonAscii[0].codePointAt(0)!.toString(16).toUpperCase()}`);
      for (const [label, re] of denied) {
        const m = re.exec(line);
        if (m) problems.push(`${loc}: ${label}: "${m[0]}"`);
      }
    });
  }
  assert.deepEqual(problems, []);
});

test('package metadata uses the single product name', () => {
  const pkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'));
  assert.equal(pkg.name, 'magicvoxel-mcp');
  assert.deepEqual(Object.keys(pkg.bin), ['magicvoxel-mcp']);
  const cfg = JSON.parse(fs.readFileSync(path.join(root, 'client-config', 'claude-desktop.json'), 'utf8'));
  assert.deepEqual(Object.keys(cfg.mcpServers), ['magicvoxel-mcp']);
});
